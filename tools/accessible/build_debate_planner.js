// Builds history/debate/planner.html: the accessible online version of the 4.3 debate planner. It lifts its CSS,
// read-aloud, voice typing, full-screen lock, zoom, supports and caret insert from history/cai-lun/accessible.html,
// as build_lesson_access.js does, and puts debate_planner_body.js in as the page's script. The page loads no
// content.js: its words are in the DATA block at the top of the body file.
//   node build_debate_planner.js
const fs = require("fs"), path = require("path");
const SRC = "C:/Tau/Year-7-Humanities-Pages/history/cai-lun/accessible.html";
const OUT = "C:/Tau/Year-7-Humanities-Pages/history/debate/planner.html";
const s = fs.readFileSync(SRC, "utf8").replace(/\r\n/g, "\n");
const between = (a, b) => { const i = s.indexOf(a); if (i < 0) throw new Error("no " + a); const j = s.indexOf(b, i + a.length); if (j < 0) throw new Error("no " + b); return s.slice(i, j); };

const extra = `
  /* debate planner: a colour per kind of box, always with its glyph and its heading */
  .k-team{--k:#1f3d47} .k-intro{--k:#7a5a00} .k-arg{--k:#175f8a} .k-reb{--k:#a3261b} .k-after{--k:#5b6669}
  .gh{background:var(--k,#1f3d47);color:#fff;border-radius:12px;padding:8px 14px;font:700 22px/1.3 Georgia,serif;margin:0 0 12px;display:flex;gap:10px;align-items:baseline;flex-wrap:wrap}
  .gh .sub{font:500 16px/1.3 system-ui,sans-serif}
  .boxes{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:14px}
  .boxes.one{grid-template-columns:minmax(0,1fr)}
  body.zbig .boxes{grid-template-columns:minmax(0,1fr)}
  .wb{border:3px solid var(--k,#1f3d47);border-radius:14px;padding:10px 12px;background:#fff}
  .k-reb .wb{border-style:dashed}
  .wb .lab{font-weight:800;color:var(--k)}
  .wb textarea{min-height:96px}
  .wb .stems .big{border-color:var(--k)}
  .looks .num{min-width:var(--tap);padding:6px 0;text-align:center}
  dl.words.one{grid-template-columns:minmax(0,1fr)}
  .cards{display:grid;gap:10px;max-height:62vh;overflow:auto;padding:3px}
  .ev{border:2px dashed #7f8a8f;border-radius:12px;padding:8px 12px;background:#fff;display:flex;gap:10px;align-items:flex-start;flex-wrap:wrap}
  .ev .rd{flex:1 1 220px;font-size:17px;line-height:1.5}
  .ev .cap{display:block;font-size:14px}
  @media screen and (min-width:861px){ body:not(.zbig) .scrollcol{max-height:calc(100vh - 290px);overflow:auto;padding:3px} body:not(.zbig) .cards{max-height:calc(100vh - 320px)} }
  #print h2 small{font-weight:400;font-size:9pt}
  /* phone width: the shared template's header and bottom bar were sized by their widest row, so the
     page scrolled sideways. Let the rows wrap instead. */
  body{grid-template-columns:minmax(0,1fr)!important}
  header.top{width:100%;max-width:100%}
  header.top>.strip{flex:0 0 100%;max-width:100%;min-width:0;width:100%}
  .bottom{flex-wrap:wrap}
  @media screen and (max-width:860px){ .boxes{grid-template-columns:minmax(0,1fr)} }
`;
const head = s.slice(0, s.indexOf("<style>"))
  .replace(/<title>[^<]*<\/title>/, "<title>Debate planner</title>")
  .replace(/<!--[\s\S]*?-->/, `<!--
  Ancient China 4.3 debate planner, online, for a student who works better on a device than on paper. The
  boxes, starters, words and sixteen evidence cards are the paper planner's, word for word
  (build43debate.js in the private Year-7-Humanities repository). There are no model answers: this is
  planning, not marking. Each box has its starter, voice typing, undo and read my answer, and is saved on
  this device as it is typed (debate43.planner.v1).

  Supports (Big buttons, Read to me, Voice typing, zoom, background colours) and the full-screen lock with no
  password are the accessible Cai Lun page's, copied from history/cai-lun/accessible.html. If that machinery is
  patched, patch this file in the same change. Built by tools/accessible/build_debate_planner.js from
  debate_planner_body.js; edit those and rebuild, do not edit this file.
  Honest interface: nothing here judges the writing. The teacher marks.
-->`);
const css = s.slice(s.indexOf("<style>"), s.indexOf("</style>")) + extra;
const shell = s.slice(s.indexOf("</style>"), s.indexOf('<script src="content.js"></script>')).replace('<span class="t">Sources and significance</span>', '<span class="t">Debate planner</span>');
const parts = {
  SPEECH: between("/* ---------- read to me", "/* ---------- the pages, in the order"),
  LOCK: between("/* ---------- the full-screen lock", '$("back").onclick'),
  ZOOM: between("const ZOOMS", "function render()"),
  SUPPORTS: between("const TINTS", "function startScreen()"),
  CARET: between("const undo = {};", "function wire(){")
};
parts.CARET = parts.CARET.replace(/drawStrip\(\);\n\}/, "drawStrip(); noteFor(key);\n}");
let body = fs.readFileSync(path.join(__dirname, "debate_planner_body.js"), "utf8");
for (const [k, v] of Object.entries(parts)) body = body.replace("/*@@" + k + "@@*/", () => v);
const out = head + css + shell + "<script>\n\"use strict\";\n" + body + "</script>\n</body>\n</html>\n";
fs.writeFileSync(OUT, out);
console.log("wrote", OUT, out.length);

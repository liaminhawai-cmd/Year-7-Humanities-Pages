// Writes vocab-data.js, every word in the Ancient China vocab hub with its lesson,
// meaning and parts, for the pop-ups in module.html. Run after the hub changes:
//   node history/daily-life/make-vocab-data.js
const fs = require("fs"), path = require("path");
const hub = fs.readFileSync(path.join(__dirname, "..", "china", "vocab-hub.html"), "utf8").split("\r\n").join("\n");
const m = hub.match(/const LESSONS = (\[[\s\S]*?\n\]);/);
if (!m) throw new Error("LESSONS not found in the hub");
const LESSONS = eval("(" + m[1] + ")");
const strip = t => String(t || "").replace(/<[^>]+>/g, "").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ").trim();
const words = [];
for (const l of LESSONS) for (const w of l.words) words.push({
  w: w.w, l: l.id, m: w.meaning,
  t: (w.tiles || []).map(([p, g]) => [p, g]),
  n: w.type === "origin" ? strip(w.note).split(/(?<=\.)\s/)[0] : "",
  f: [...new Set((w.forms || []).map(f => f[0]).concat(w.w))]
});
const out = `/* GENERATED by make-vocab-data.js from history/china/vocab-hub.html. Do not edit:
   change the hub and run the script again. ${words.length} words, ${LESSONS.length} lessons. */
const HUB_KEY = "ancientchina.vocabhub.v1";
const HUB_LESSONS = ${JSON.stringify(LESSONS.map(l => ({ id: l.id, title: l.title })))};
const HUB_WORDS = ${JSON.stringify(words)};
`;
fs.writeFileSync(path.join(__dirname, "vocab-data.js"), out);
console.log("wrote vocab-data.js:", words.length, "words");
